// Function to replace text and save as JPG
function replaceTextAndSave(text, index) {
  var doc = app.activeDocument;
  var textLayer = doc.artLayers.getByName("name");
  // Replace with your text layer name
  textLayer.textItem.contents = text;
  // Save the file incrementally
  var saveFile = new File(doc.path + "/" + "output_" + index + ".jpg");
  var jpgSaveOptions = new JPEGSaveOptions();
  jpgSaveOptions.quality = 12;
  //Set the quality (0-12)
  doc.saveAs(saveFile, jpgSaveOptions, true, Extension.LOWERCASE);
}
